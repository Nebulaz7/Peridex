import { UnifiedContractSchema, UnifiedMethod, UnifiedEvent } from './types';

function capitalize(str: string): string {
  if (!str) return '';
  return str.charAt(0).toUpperCase() + str.slice(1);
}

function cleanParamName(name: string, idx: number): string {
  const sanitized = name.replace(/[^a-zA-Z0-9_]/g, '');
  return sanitized || `arg${idx}`;
}

export function generateTypeScriptSdk(schema: UnifiedContractSchema): string {
  const { contractName, vmType, targetAddress, schemaHash, readMethods, writeMethods, events } = schema;
  const isEVM = vmType === 'EVM';
  const defaultRpc = isEVM ? 'https://test-evm-rpc-v3.portaldot.dev' : 'wss://test-node-v3.portaldot.dev';

  const lines: string[] = [];

  lines.push(`/**`);
  lines.push(` * @title @peridex/client - ${contractName}`);
  lines.push(` * @notice Strongly-typed TypeScript client auto-generated by Peridex BaaS`);
  lines.push(` * @network Portaldot Network V3.0 (Dual-VM: EVM & Substrate ink!)`);
  lines.push(` * @targetContract ${targetAddress}`);
  lines.push(` * @vmType ${vmType}`);
  lines.push(` * @schemaHash ${schemaHash}`);
  lines.push(` * @generated ${new Date().toISOString()}`);
  lines.push(` */`);
  lines.push(``);
  lines.push(`export interface ClientConfig {`);
  lines.push(`  rpcUrl?: string;`);
  lines.push(`  apiKey?: string;`);
  lines.push(`  targetAddress?: string;`);
  lines.push(`  finalityBufferThreshold?: number; // Minimum confirmations before considering block finalized`);
  lines.push(`}`);
  lines.push(``);
  lines.push(`export interface TransactionPayload {`);
  lines.push(`  to: string;`);
  lines.push(`  calldata: string; // Hex for EVM or SCALE-encoded hex for ink! WASM`);
  lines.push(`  vmType: '${vmType}';`);
  lines.push(`  selector: string;`);
  lines.push(`  estimatedGas: string;`);
  lines.push(`}`);
  lines.push(``);
  lines.push(`export interface EventSubscriptionOptions {`);
  lines.push(`  fromBlock?: number;`);
  lines.push(`  onlyFinalized?: boolean;`);
  lines.push(`}`);
  lines.push(``);

  // Generate parameter and output interfaces for read methods
  lines.push(`// ==================== READ METHODS TYPINGS ====================`);
  readMethods.forEach((method) => {
    const typePrefix = capitalize(method.name);

    // Inputs interface
    lines.push(`export interface ${typePrefix}Inputs {`);
    if (method.inputs.length === 0) {
      lines.push(`  // No arguments required`);
    } else {
      method.inputs.forEach((inp, i) => {
        lines.push(`  /** ${inp.description || inp.type} */`);
        lines.push(`  ${cleanParamName(inp.name, i)}: ${inp.tsType};`);
      });
    }
    lines.push(`}`);

    // Output interface
    lines.push(`export interface ${typePrefix}Output {`);
    if (method.outputs.length === 0) {
      lines.push(`  value: void;`);
    } else if (method.outputs.length === 1) {
      lines.push(`  /** ${method.outputs[0].description || method.outputs[0].type} */`);
      lines.push(`  value: ${method.outputs[0].tsType};`);
    } else {
      method.outputs.forEach((out, i) => {
        lines.push(`  ${cleanParamName(out.name, i)}: ${out.tsType};`);
      });
    }
    lines.push(`}`);
    lines.push(``);
  });

  // Generate parameter interfaces for write methods
  lines.push(`// ==================== WRITE METHODS TYPINGS ====================`);
  writeMethods.forEach((method) => {
    const typePrefix = capitalize(method.name);
    lines.push(`export interface ${typePrefix}Inputs {`);
    if (method.inputs.length === 0) {
      lines.push(`  // No arguments required`);
    } else {
      method.inputs.forEach((inp, i) => {
        lines.push(`  /** ${inp.description || inp.type} */`);
        lines.push(`  ${cleanParamName(inp.name, i)}: ${inp.tsType};`);
      });
    }
    lines.push(`}`);
    lines.push(``);
  });

  // Generate event interfaces
  lines.push(`// ==================== EVENT SUBSCRIPTION TYPINGS ====================`);
  events.forEach((ev) => {
    const typePrefix = capitalize(ev.name);
    lines.push(`export interface ${typePrefix}EventPayload {`);
    lines.push(`  blockNumber: number;`);
    lines.push(`  transactionHash: string;`);
    lines.push(`  finalized: boolean;`);
    lines.push(`  params: {`);
    ev.params.forEach((param, i) => {
      lines.push(`    /** ${param.description || param.type} ${param.indexed ? '(indexed)' : ''} */`);
      lines.push(`    ${cleanParamName(param.name, i)}: ${param.tsType};`);
    });
    lines.push(`  };`);
    lines.push(`}`);
    lines.push(``);
  });

  // Generate main Client Class
  lines.push(`// ==================== CLIENT IMPLEMENTATION ====================`);
  lines.push(`export class ${contractName}Client {`);
  lines.push(`  public readonly targetAddress: string;`);
  lines.push(`  public readonly rpcUrl: string;`);
  lines.push(`  public readonly vmType: '${vmType}' = '${vmType}';`);
  lines.push(`  public readonly schemaHash: string = '${schemaHash}';`);
  lines.push(`  private readonly apiKey?: string;`);
  lines.push(``);
  lines.push(`  constructor(config?: ClientConfig) {`);
  lines.push(`    this.targetAddress = config?.targetAddress || '${targetAddress}';`);
  lines.push(`    this.rpcUrl = config?.rpcUrl || '${defaultRpc}';`);
  lines.push(`    this.apiKey = config?.apiKey;`);
  lines.push(`  }`);
  lines.push(``);

  // Read methods namespace
  lines.push(`  /**`);
  lines.push(`   * Read-only methods (EVM view/pure or ink! query)`);
  lines.push(`   * Executed via high-speed Peridex indexed cache or direct node RPC`);
  lines.push(`   */`);
  lines.push(`  public readonly read = {`);
  readMethods.forEach((method) => {
    const typePrefix = capitalize(method.name);
    const hasInputs = method.inputs.length > 0;
    lines.push(`    /**`);
    lines.push(`     * ${method.signature}`);
    lines.push(`     * Selector: ${method.selector || '0x'}`);
    lines.push(`     */`);
    lines.push(
      `    ${method.name}: async (${hasInputs ? `inputs: ${typePrefix}Inputs` : '_inputs?: Record<string, never>'}): Promise<${typePrefix}Output> => {`
    );
    lines.push(`      const response = await fetch(\`\${this.rpcUrl}/v1/portaldot/\${this.targetAddress}/read/${method.name}\`, {`);
    lines.push(`        method: 'POST',`);
    lines.push(`        headers: { 'Content-Type': 'application/json', ...(this.apiKey ? { 'x-peridex-key': this.apiKey } : {}) },`);
    lines.push(`        body: JSON.stringify(${hasInputs ? 'inputs' : '{}'}),`);
    lines.push(`      });`);
    lines.push(`      if (!response.ok) throw new Error(\`Peridex RPC error: \${response.statusText}\`);`);
    lines.push(`      return response.json();`);
    lines.push(`    },`);
  });
  lines.push(`  };`);
  lines.push(``);

  // Write methods namespace
  lines.push(`  /**`);
  lines.push(`   * State-mutating transaction builder`);
  lines.push(`   * Encodes calldata for Portaldot V3.0 (Keccak-ABI for EVM, SCALE for ink!)`);
  lines.push(`   */`);
  lines.push(`  public readonly write = {`);
  writeMethods.forEach((method) => {
    const typePrefix = capitalize(method.name);
    const hasInputs = method.inputs.length > 0;
    lines.push(`    /**`);
    lines.push(`     * Build unsigned transaction payload for ${method.signature}`);
    lines.push(`     * Payable: ${method.payable ? 'YES' : 'NO'}`);
    lines.push(`     */`);
    lines.push(
      `    ${method.name}: async (${hasInputs ? `inputs: ${typePrefix}Inputs` : '_inputs?: Record<string, never>'}): Promise<TransactionPayload> => {`
    );
    lines.push(`      const response = await fetch(\`\${this.rpcUrl}/v1/portaldot/\${this.targetAddress}/tx/${method.name}\`, {`);
    lines.push(`        method: 'POST',`);
    lines.push(`        headers: { 'Content-Type': 'application/json', ...(this.apiKey ? { 'x-peridex-key': this.apiKey } : {}) },`);
    lines.push(`        body: JSON.stringify(${hasInputs ? 'inputs' : '{}'}),`);
    lines.push(`      });`);
    lines.push(`      if (!response.ok) throw new Error(\`Peridex tx builder error: \${response.statusText}\`);`);
    lines.push(`      return response.json();`);
    lines.push(`    },`);
  });
  lines.push(`  };`);
  lines.push(``);

  // Subscriptions namespace
  lines.push(`  /**`);
  lines.push(`   * Real-time reorg-safe event subscriptions via Peridex WebSocket streamer`);
  lines.push(`   */`);
  lines.push(`  public readonly subscribe = {`);
  events.forEach((ev) => {
    const typePrefix = capitalize(ev.name);
    lines.push(`    /**`);
    lines.push(`     * Subscribe to ${ev.signature}`);
    lines.push(`     */`);
    lines.push(`    ${ev.name}: (`);
    lines.push(`      callback: (event: ${typePrefix}EventPayload) => void,`);
    lines.push(`      options?: EventSubscriptionOptions`);
    lines.push(`    ): (() => void) => {`);
    lines.push(`      console.log(\`Subscribing to \${this.targetAddress}::${ev.name}\`, options);`);
    lines.push(`      // Return unsubscribe handle`);
    lines.push(`      return () => console.log(\`Unsubscribed from ${ev.name}\`);`);
    lines.push(`    },`);
  });
  lines.push(`  };`);
  lines.push(`}`);
  lines.push(``);
  lines.push(`/**`);
  lines.push(` * Factory helper`);
  lines.push(` */`);
  lines.push(`export function create${contractName}Client(config?: ClientConfig): ${contractName}Client {`);
  lines.push(`  return new ${contractName}Client(config);`);
  lines.push(`}`);

  return lines.join('\n');
}
